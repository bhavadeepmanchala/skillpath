CREATE TABLE skill (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    category VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE skill_alias (
    skill_id BIGINT NOT NULL,
    alias VARCHAR(255) NOT NULL,
    PRIMARY KEY (skill_id, alias),
    CONSTRAINT fk_skill_alias_skill FOREIGN KEY (skill_id) REFERENCES skill (id) ON DELETE CASCADE
);

CREATE TABLE role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    sector VARCHAR(100) NOT NULL
);

CREATE TABLE district (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    state VARCHAR(100) NOT NULL
);

CREATE TABLE job_posting (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL,
    district_id BIGINT NOT NULL,
    posted_on DATE NOT NULL,
    level VARCHAR(50),
    CONSTRAINT fk_job_posting_role FOREIGN KEY (role_id) REFERENCES role (id) ON DELETE CASCADE,
    CONSTRAINT fk_job_posting_district FOREIGN KEY (district_id) REFERENCES district (id) ON DELETE CASCADE
);

CREATE TABLE posting_skill (
    posting_id BIGINT NOT NULL,
    skill_id BIGINT NOT NULL,
    required_level VARCHAR(50),
    PRIMARY KEY (posting_id, skill_id),
    CONSTRAINT fk_posting_skill_posting FOREIGN KEY (posting_id) REFERENCES job_posting (id) ON DELETE CASCADE,
    CONSTRAINT fk_posting_skill_skill FOREIGN KEY (skill_id) REFERENCES skill (id) ON DELETE CASCADE
);

CREATE TABLE course (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    duration_weeks INT NOT NULL,
    sector VARCHAR(100) NOT NULL
);

CREATE TABLE course_skill (
    course_id BIGINT NOT NULL,
    skill_id BIGINT NOT NULL,
    taught_level VARCHAR(50),
    PRIMARY KEY (course_id, skill_id),
    CONSTRAINT fk_course_skill_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE,
    CONSTRAINT fk_course_skill_skill FOREIGN KEY (skill_id) REFERENCES skill (id) ON DELETE CASCADE
);

CREATE TABLE course_role (
    course_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    PRIMARY KEY (course_id, role_id),
    CONSTRAINT fk_course_role_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE,
    CONSTRAINT fk_course_role_role FOREIGN KEY (role_id) REFERENCES role (id) ON DELETE CASCADE
);

CREATE TABLE course_offering (
    course_id BIGINT NOT NULL,
    district_id BIGINT NOT NULL,
    "year" INT NOT NULL,
    seats INT NOT NULL,
    trainers INT NOT NULL,
    PRIMARY KEY (course_id, district_id, "year"),
    CONSTRAINT fk_course_offering_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE,
    CONSTRAINT fk_course_offering_district FOREIGN KEY (district_id) REFERENCES district (id) ON DELETE CASCADE
);

CREATE TABLE placement_outcome (
    course_id BIGINT NOT NULL,
    district_id BIGINT NOT NULL,
    "year" INT NOT NULL,
    placed_pct DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (course_id, district_id, "year"),
    CONSTRAINT fk_placement_outcome_course FOREIGN KEY (course_id) REFERENCES course (id) ON DELETE CASCADE,
    CONSTRAINT fk_placement_outcome_district FOREIGN KEY (district_id) REFERENCES district (id) ON DELETE CASCADE
);

CREATE TABLE employer_validation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL,
    skill_id BIGINT NOT NULL,
    status VARCHAR(50) NOT NULL,
    note VARCHAR(1000),
    CONSTRAINT fk_employer_validation_role FOREIGN KEY (role_id) REFERENCES role (id) ON DELETE CASCADE,
    CONSTRAINT fk_employer_validation_skill FOREIGN KEY (skill_id) REFERENCES skill (id) ON DELETE CASCADE
);

CREATE TABLE demand_monthly (
    district_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    skill_id BIGINT NOT NULL,
    "month" VARCHAR(7) NOT NULL,
    postings_with_skill INT NOT NULL,
    postings_total INT NOT NULL,
    PRIMARY KEY (district_id, role_id, skill_id, "month"),
    CONSTRAINT fk_demand_monthly_district FOREIGN KEY (district_id) REFERENCES district (id) ON DELETE CASCADE,
    CONSTRAINT fk_demand_monthly_role FOREIGN KEY (role_id) REFERENCES role (id) ON DELETE CASCADE,
    CONSTRAINT fk_demand_monthly_skill FOREIGN KEY (skill_id) REFERENCES skill (id) ON DELETE CASCADE
);

CREATE TABLE training_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    district_id BIGINT NOT NULL,
    generated_on TIMESTAMP NOT NULL,
    payload TEXT NOT NULL,
    CONSTRAINT fk_training_plan_district FOREIGN KEY (district_id) REFERENCES district (id) ON DELETE CASCADE
);

CREATE INDEX idx_job_posting_role_district_posted ON job_posting (role_id, district_id, posted_on);
CREATE INDEX idx_demand_monthly_role_district_month ON demand_monthly (role_id, district_id, "month");
